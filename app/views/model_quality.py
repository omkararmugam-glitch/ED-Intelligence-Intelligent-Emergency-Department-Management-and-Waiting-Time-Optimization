"""Model quality and fairness, in sentences before tables.

Everything on this page describes how the models were *evaluated* on held-out data.
It is a property of a completed pipeline run, not of the department now, and the
page says so at the top -- a reader otherwise reasonably assumes every number on a
dashboard is current.

The two findings that do not flatter the service are stated as plainly as the ones
that do: the 90% ranges cover about 85% of cases in testing, and for the two most
urgent acuity levels the long-wait warning catches nothing at all, because there
were almost no long waits at those levels to learn from.
"""

from __future__ import annotations

import pandas as pd
import streamlit as st

from app import artifacts, components, theme
from app.views import _shared

#: Acuity levels where the long-wait warning cannot be trusted, and why.
UNRELIABLE_LEVELS = (1, 2)


def render() -> None:
    """Draw the Model quality and fairness page."""
    components.page_header(
        "Quality and equity",
        "How accurate the estimates were on data the models had never seen.",
        breadcrumb=("Clinical intelligence", "Quality and equity"),
        icon_name="quality",
    )

    theme.info_callout(
        "These are measurements from the last completed analysis, not a reading of "
        "the department now. They say how well the models did on held-out data.",
        level="info",
    )

    if not artifacts.exists():
        _shared.needs_analysis("quality measurements")
        return

    _accuracy()
    st.divider()
    _ranges()
    st.divider()
    _long_wait_warning()
    st.divider()
    _fairness()
    st.divider()
    _data_quality()




# ------------------------------------------------------------------- how accurate


def _accuracy() -> None:
    """The headline: our error against a simple average."""
    quality = artifacts.wait_model_quality()
    if quality is None:
        _shared.needs_analysis("accuracy measurements")
        return

    model_mae = quality["model_mae"]
    baseline_mae = quality["baseline_mae"]

    theme.section_header("How close the wait estimates were", "")
    st.markdown(
        f"**The estimate is off by about {theme.minutes(model_mae)} on average, "
        f"against {theme.minutes(baseline_mae)} for simply using the average wait.** "
        f"That is measured on {theme.count(quality['n_test'])} patients the models "
        "had never seen."
    )

    columns = st.columns(3, gap="small")
    with columns[0]:
        theme.kpi_card(
            "Typical error, this service",
            theme.minutes(model_mae),
            help=(
                "Mean absolute error: the average size of the gap between the "
                "estimate and what actually happened."
            ),
        )
    with columns[1]:
        theme.kpi_card(
            "Typical error, simple average",
            theme.minutes(baseline_mae),
            help="What you would get by quoting the average wait to everyone.",
        )
    with columns[2]:
        theme.kpi_card(
            "Improvement",
            theme.percent(quality["improvement"]),
            help="How much smaller this service's typical error is.",
        )
        theme.render_pill("good", "Better than the simple average")

    caveat = quality.get("ablation_caveat")
    if caveat:
        theme.info_callout(
            "Most of that accuracy comes from knowing how congested the department "
            "is at the moment the patient arrives. On synthetic data that counts for "
            "more than it would in reality, because the data was generated by "
            "simulating a queue. Treat the direction as sound and the size as an "
            "upper bound.",
            level="watch",
            title="Why the improvement is an upper bound.",
        )
        with theme.technical_details("the full caveat as the pipeline recorded it"):
            st.code(caveat, language=None)


# ----------------------------------------------------------------------- the ranges


def _ranges() -> None:
    """How often the stated range actually contained the answer, per acuity."""
    frame = artifacts.coverage_by_triage()
    quality = artifacts.wait_model_quality()
    if frame is None or frame.empty:
        st.caption("No interval measurements were recorded by the last analysis.")
        return

    theme.section_header(
        "How often the range was right",
        "A 90% range should contain the true wait about 9 times in 10.",
    )

    overall = frame.loc[frame["triage_level"].astype(str) == "overall"]
    if not overall.empty:
        measured = float(overall["empirical_coverage"].iloc[0])
        nominal = float(overall["nominal_coverage"].iloc[0])
        short = measured < nominal - 0.02

        columns = st.columns(2, gap="medium")
        with columns[0]:
            theme.kpi_card(
                "Ranges labelled",
                theme.percent(nominal, places=0),
                help="What the service claims its ranges cover.",
            )
        with columns[1]:
            theme.kpi_card(
                "Ranges measured",
                theme.percent(measured),
                help="How often the true wait actually fell inside the range.",
            )
            theme.render_pill(
                "watch" if short else "good",
                "Narrower than advertised" if short else "As advertised",
            )

        if short:
            theme.info_callout(
                f"The ranges are labelled {theme.percent(nominal, places=0)} but contained the "
                f"true wait "
                f"{theme.percent(measured)} of the time on held-out data. They are slightly too "
                "narrow, so treat the top of a range as a little optimistic rather "
                "than as a worst case.",
                level="watch",
                title="The ranges are a little narrow.",
            )

    per_level = frame.loc[frame["triage_level"].astype(str) != "overall"].copy()
    if not per_level.empty:
        display = pd.DataFrame(
            {
                "Urgency": per_level["triage_level"].astype(str),
                "Patients measured": [theme.count(n) for n in per_level["n"]],
                "Range was right": [
                    theme.percent(v) for v in per_level["empirical_coverage"]
                ],
                "Typical range width": [
                    theme.minutes(v) for v in per_level["mean_width_minutes"]
                ],
            }
        )
        st.dataframe(display, use_container_width=True, hide_index=True)
        st.caption(
            "A wider range means that group's wait is harder to predict. The most "
            "urgent patients are seen quickly and predictably, so their ranges are "
            "narrow."
        )


# ------------------------------------------------------- the long-wait warning


def _long_wait_warning() -> None:
    """Where the long-wait flag works and where it does not."""
    frame = artifacts.triage_thresholds()
    if frame is None or frame.empty:
        return

    theme.section_header(
        "The long-wait warning",
        "How often it catches a patient who really did wait a long time.",
    )

    pooled = frame.loc[frame["rule"] == "pooled"].copy()
    rows = []
    for _, row in pooled.iterrows():
        scope = str(row["scope"])
        if scope == "overall":
            continue
        positives = _as_int(row.get("n_positive"))
        recall = row.get("recall")
        trustworthy = positives is not None and positives >= 50
        rows.append(
            {
                "Urgency": scope,
                "Long waits in the test data": theme.count(positives),
                "Caught by the warning": theme.percent(recall)
                if trustworthy
                else "Not measurable",
                "Trustworthy": "Yes" if trustworthy else "No — too few cases",
            }
        )

    if rows:
        st.dataframe(pd.DataFrame(rows), use_container_width=True, hide_index=True)

    theme.info_callout(
        "Long waits are almost entirely an urgency 3 to 5 phenomenon. In the test "
        "data the two most urgent levels had almost no long waits at all, so there "
        "was nothing to tune a warning on and nothing to measure it against. For "
        "those two levels, the absence of a warning tells you nothing — do not read "
        "it as reassurance.",
        level="act",
        title="The warning does not work for the most urgent patients.",
    )

    with theme.technical_details():
        st.caption(
            "Per-acuity thresholds as the pipeline fitted them, including the levels "
            "that fell back to the pooled threshold "
            "."
        )
        st.dataframe(frame, use_container_width=True, hide_index=True)


# -------------------------------------------------------------------- fairness


def _fairness() -> None:
    """Subgroup differences, with the small-sample warning attached."""
    frame = artifacts.fairness_table()
    theme.section_header(
        "Fairness across groups",
        "Accuracy measured separately for each group, with the case counts.",
    )

    if frame is None or frame.empty:
        st.caption("No fairness measurements were recorded by the last analysis.")
        return

    st.markdown(
        "A missed long wait is the error that matters here: it means a patient who "
        "really did wait a long time was not flagged. The table shows that rate by "
        "group."
    )

    display = frame.copy()
    if "n_positive" in display.columns:
        small = display["n_positive"] < 50
        display["Reliable?"] = [
            "No — too few cases" if flag else "Yes" for flag in small
        ]
    st.dataframe(display, use_container_width=True, hide_index=True)

    theme.info_callout(
        "A missed-long-wait rate is worked out only from patients who actually had a "
        "long wait, so a group with few of those has a rate that swings wildly on a "
        "handful of cases. Read the number of cases before reading the rate: any row "
        "marked unreliable is not evidence of a difference, in either direction.",
        level="watch",
        title="Small groups first.",
    )


# ----------------------------------------------------------------- data quality


def _data_quality() -> None:
    """How much of the input survived validation, and what was dropped."""
    frame = artifacts.data_quality_summary()
    theme.section_header("The data behind these numbers", "")

    if frame is None or frame.empty:
        st.caption("No validation summary was recorded by the last analysis.")
        return

    def value(detail_contains: str) -> int | None:
        rows = frame.loc[frame["detail"].str.contains(detail_contains, case=False, na=False)]
        return _as_int(rows["count"].iloc[0]) if not rows.empty else None

    read = value("rows read from source")
    valid = value("rows valid after checks")
    dropped = value("rows dropped")
    lwbs = value("left without being seen")

    columns = st.columns(4, gap="small")
    with columns[0]:
        theme.kpi_card("Records read", theme.count(read))
    with columns[1]:
        theme.kpi_card(
            "Usable after checks",
            theme.count(valid),
            help="Records that passed every validity check.",
        )
    with columns[2]:
        theme.kpi_card(
            "Set aside",
            theme.count(dropped),
            help="Records with a problem that made them unusable.",
        )
    with columns[3]:
        theme.kpi_card(
            "Left before being seen",
            theme.count(lwbs),
            help=(
                "These patients waited longest of all, and the wait models cannot "
                "learn from them, which is why long waits are under-estimated."
            ),
        )

    with theme.technical_details():
        st.caption("Validation summary.")
        st.dataframe(frame, use_container_width=True, hide_index=True)

        drift = artifacts.table("conformal_static_vs_rolling.csv")
        if drift is not None:
            st.caption(
                "Interval coverage when calibrated once versus recalibrated as "
                "demand drifts:"
            )
            st.dataframe(drift, use_container_width=True, hide_index=True)


def _as_int(value) -> int | None:
    """An int, or None for anything that is not one."""
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    if number != number:
        return None
    return int(number)
